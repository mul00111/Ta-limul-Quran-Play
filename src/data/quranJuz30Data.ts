export interface SurahPuzzleItem {
  id: string;
  title: string;
  arabicName: string;
  words: string[];
  audioUrl?: string;
}

// Helper to construct audio URL
const getAudioUrl = (surah: number, ayah: number) => {
  const sStr = String(surah).padStart(3, '0');
  const aStr = String(ayah).padStart(3, '0');
  return `https://everyayah.com/data/Alafasy_128kbps/${sStr}${aStr}.mp3`;
};

// Helper to format item
const createAyah = (prefix: string, surahNum: number, ayahNum: number, surahTitle: string, text: string): SurahPuzzleItem => {
  const words = text.trim().split(/\s+/).filter(Boolean);
  return {
    id: `${prefix}-${ayahNum}`,
    title: `${surahTitle} (آیت ${ayahNum})`,
    arabicName: text,
    words,
    audioUrl: getAudioUrl(surahNum, ayahNum)
  };
};

